"""
What you're reading, from your website's reading list.

Your site (elizabethqiu.com) keeps every Goodreads shelf in src/data/books.ts, generated by its
scripts/import-books.mjs from Goodreads. loop reads that file directly, so there's no API to build.
It updates whenever you re-run the site's import script.

Setting: books_file (default ~/Documents/GithubProjects/site/src/data/books.ts).
"""
import json
from pathlib import Path

DEFAULT = Path.home() / "Documents" / "GithubProjects" / "site" / "src" / "data" / "books.ts"
_cache: dict = {}


def path(settings: dict) -> Path:
    return Path(settings.get("books_file") or DEFAULT).expanduser()


def load(settings: dict) -> list[dict]:
    p = path(settings)
    if not p.exists():
        return []
    mtime = p.stat().st_mtime
    if _cache.get("key") == (str(p), mtime):
        return _cache["books"]
    books = []
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.strip().rstrip(",")
        if line.startswith("{") and line.endswith("}") and '"title"' in line:
            try:
                books.append(json.loads(line))
            except ValueError:
                continue
    _cache.update(key=(str(p), mtime), books=books)
    return books


def summary(settings: dict) -> dict:
    books = load(settings)
    p = path(settings)
    shelf = lambda s: [b for b in books if b.get("shelf") == s]
    read = shelf("read")
    return {
        "connected": bool(books),
        "file": str(p),
        "updated": p.stat().st_mtime if p.exists() else None,
        "reading": shelf("reading"),
        "favorites": [b for b in read if b.get("rating") == 5][:12],
        "counts": {"reading": len(shelf("reading")), "read": len(read), "to_read": len(shelf("to-read")),
                   "rated": sum(1 for b in read if b.get("rating"))},
    }
